export function getJurisdiction(code: string): Jurisdiction {
  return jurisdictions.find((j) => j.code === code) ?? jurisdictions[0];
}

export function getRegionColor(region: Region): string {
  switch (region) {
    case 'Europe':
      return 'accent.indigo';
    case 'UK':
      return 'accent.emerald';
    case 'APAC':
      return 'accent.amber';
    case 'Maldives & Sri Lanka':
      return 'accent.crimson';
  }
}
